def stage_tree(root: pathlib.Path, dest: pathlib.Path) -> list[str]:
    """Copy `HARNESS_TREE` from `root` into `dest`. An empty return means the tree is complete.

    A missing entry is CANNOT RUN, never a quieter, smaller tree. The control run would catch
    it either way — a guard whose subject was not copied exits 2 and `control_is_green` goes
    false — but it would name the wrong cause, reporting the GUARD as broken when the harness
    was the thing that failed to stage its subject. That is the "plausible and wrong" shape
    this file already refuses elsewhere, so say which path was absent instead.
    """
    problems = []
    for rel in HARNESS_TREE:
        src = root / rel
        if not src.exists():
            problems.append(f"CANNOT RUN — {rel} is missing under {root}, so the mutation "
                            f"tree would be incomplete and every verdict below it an "
                            f"artefact. TREAT THIS AS NOT CHECKED")
            continue
        dst = dest / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(src, dst)
    return problems


# The home-resolution routes `$HOME` does NOT govern — see `child_env`'s scope note.
# Turning that one-off grep into a standing check is the point: a convention catches what
# somebody reads, a script catches what is there. The subject is the MUTATION TARGETS,
# because those are the files a mutation can rewrite into a write.
HOME_ESCAPES = [
    (re.compile(r"\bgetpw(uid|nam)\b"),
     "pwd.getpwuid()/getpwnam() reads the account home from the password database "  # not-a-home-escape: this IS the rule's own reason text
     "and ignores $HOME entirely"),
    (re.compile(r"expanduser\(\s*[\"'][^\"']*~\w"),
     "expanduser('~<user>') names a specific user's home and ignores $HOME"),
    (re.compile(r"[\"'][^\"']*(?:/Users/|/home/)\w"),
     "a hardcoded absolute home path does not move when $HOME does"),
]


# A line carrying this marker plus a reason is not scanned. Needed the moment this file
# became a mutation target itself (backlog #74): the cases that PROVE `home_escapes` works
# necessarily contain each flagged route verbatim as fixture strings, and a text
# scanner cannot tell a fixture from a call. Exempting the whole file would excuse the one
# file that most needs the check; a per-line written reason keeps every exemption visible
# to `grep` and countable. A bare marker with no reason does NOT exempt.
ESCAPE_EXEMPT = re.compile(r"#\s*not-a-home-escape:\s*\S")


def home_escapes(src: str) -> list[str]:
    """Why `src` could still reach the real home under a redirected $HOME. Empty is good.

    Static and therefore incomplete — it reads source, so a route assembled at runtime
    slips past. It is a ratchet against the routes that are cheap to write by accident,
    not a proof. Stated here rather than left for someone to discover.

    ⚠ TOKENISED, not line-matched, and the Codex half of this branch's review is why. A
    plain text filter had TWO bypasses, both measured: the marker inside a STRING LITERAL
    (`s = "# not-a-home-escape:"`) silently dropped the whole physical line including a
    real password-database lookup before it; and a marker written onto a line of live code
    exempted the live code. So the marker now counts only as a genuine COMMENT token, and it exempts a
    line only when the route disappears once every STRING token is blanked — i.e. the
    route lives in string DATA (a fixture) and not in code that runs. An executable route
    cannot be exempted at all, by anyone, with any comment.

    A file that will not tokenise is scanned RAW with no exemptions honoured: unparseable
    is a reason to be stricter, never a reason to pass.
    """
    try:
        toks = list(tokenize.generate_tokens(io.StringIO(src).readline))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return [why for rx, why in HOME_ESCAPES if rx.search(src)]
    full: dict[int, str] = {}
    blanked: dict[int, str] = {}
    exempt: set[int] = set()
    for t in toks:
        ln = t.start[0]
        if t.type == tokenize.COMMENT:
            if ESCAPE_EXEMPT.search(t.string):
                exempt.add(ln)
            continue
        if t.type in (tokenize.NL, tokenize.NEWLINE, tokenize.INDENT,
                      tokenize.DEDENT, tokenize.ENDMARKER):
            continue
        full[ln] = full.get(ln, "") + t.string
        if t.type != tokenize.STRING:
            blanked[ln] = blanked.get(ln, "") + t.string
    out = []
    for rx, why in HOME_ESCAPES:
        for ln, text in full.items():
            if not rx.search(text):
                continue
            if ln in exempt and not rx.search(blanked.get(ln, "")):
                continue          # fixture data on a line with a written reason
            out.append(why)
            break
    return out


