MANIFEST_DIR = "scripts/mutations"


def load_manifests(root: pathlib.Path) -> tuple[list[dict], list[str]]:
    """Read every `scripts/mutations/<stem>.json` under `root`.

    The FILENAME is the authority on which script an entry targets; each entry's `file`
    key must agree with it. Two statements of one fact, checked against each other — a
    copy-paste that retargets an entry is caught, where a single unchecked statement
    would simply be believed.

    An empty manifest, a missing target, and no manifests at all are all REFUSALS. A
    mutation run that measured nothing must never be readable as one that found nothing.
    """
    d = root / MANIFEST_DIR
    if not d.is_dir():
        return [], [f"CANNOT RUN — no manifests: {d} is not a directory"]
    files = sorted(d.glob("*.json"))
    if not files:
        return [], [f"CANNOT RUN — no manifests found in {d}"]
    out, problems = [], []
    for man in files:
        target = f"scripts/{man.stem}.py"
        if not (root / target).is_file():
            problems.append(f"{man.name}: target {target} does not exist under {root}")
            continue
        try:
            entries = json.loads(man.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            problems.append(f"{man.name}: not valid JSON — {exc}")
            continue
        if not isinstance(entries, list) or not entries:
            problems.append(f"{man.name}: no entries — an empty manifest measures nothing")
            continue
        seen_names, seen_anchors = set(), set()
        for e in entries:
            # ⟲ IDENTITY, not just cardinality. EXPECTED_MUTATIONS pins HOW MANY entries a
            # script has; on its own that is satisfied by replacing one entry with a copy of
            # another — count unchanged, coverage silently narrowed. Found in branch review
            # by Codex, reproduced: entry 32 swapped for a duplicate of entry 1, still green.
            # This is the same error as asserting a threshold's presence instead of measuring
            # the ratio: a proxy for the property rather than the property.
            nm, anchors = e.get("name"), tuple(f for f, _ in e.get("edits", []))
            if nm in seen_names:
                problems.append(f"{man.name}: duplicate mutation name {nm!r} — two entries "
                                f"cannot both be the guard for the same named behaviour, and "
                                f"a duplicate keeps the count while shrinking coverage")
                continue
            if anchors and anchors in seen_anchors:
                problems.append(f"{man.name}: entry {nm!r} repeats the edit anchors of an "
                                f"earlier entry — it measures nothing new")
                continue
            seen_names.add(nm)
            seen_anchors.add(anchors)
            if e.get("file") != target:
                problems.append(f"{man.name}: entry {e.get('name')!r} has file "
                                f"{e.get('file')!r}, which disagrees with the manifest "
                                f"name (expected {target!r})")
                continue
            out.append(e)
    return out, problems


def mutate_delivered(root: pathlib.Path) -> tuple[bool, list[str], dict]:
    """Mutate the DELIVERED scripts, not a copy assembled from a document.

    The whole `scripts/` tree is copied because these scripts import each other as
    siblings and resolve a repo root from their own path; copying only the targeted
    files gives a red control, and a mutation table over a red control is not evidence.
    """
    muts, problems = load_manifests(root)
    ev = {"files": {}, "mutations": [], "survivors": [], "tally": {}, "compared": None}
    if problems:
        return False, problems, ev
    counts = {}
    for m in muts:
        counts[m["file"]] = counts.get(m["file"], 0) + 1
    drift = []
    for target, want in sorted(EXPECTED_MUTATIONS.items()):
        got = counts.get(target, 0)
        if got != want:
            drift.append(f"{target}: manifest holds {got} mutation(s), expected {want}. "
                         f"Coverage cannot change silently — if this is deliberate, change "
                         f"EXPECTED_MUTATIONS in check-plan-code.py in the SAME commit and "
                         f"say why in the message")
    for target in sorted(set(counts) - set(EXPECTED_MUTATIONS)):
        drift.append(f"{target}: {counts[target]} mutation(s) but no declared count — add it "
                     f"to EXPECTED_MUTATIONS so its coverage cannot shrink unnoticed")
    # A target that resolves the home directory by a route `$HOME` does not govern would
    # make `child_env`'s guarantee false without changing anything `child_env` can see.
    for target in sorted(counts):
        try:
            src = (root / target).read_text(encoding="utf-8")
        except OSError as exc:
            drift.append(f"{target}: CANNOT RUN — unreadable ({exc}), so its home-escape "
                         f"routes were NOT CHECKED")
            continue
        for why in home_escapes(src):
            drift.append(f"{target}: {why}. The mutation harness redirects $HOME so a "
                         f"mutation cannot reach the reader's pages under ~/explainers/, "
                         f"and this route steps around that. Use pathlib.Path.home()")
    # ⚠ AND THE REPLACEMENT TEXT. Scanning the target alone reads the code as it is
    # BEFORE the mutation — and a mutation is the one thing that rewrites it, so a clean
    # target says nothing about what the manifest is about to put there. Found by the
    # coordinator half of this branch's review, against the fix written for the Codex
    # half an hour earlier: correcting a premise is not the same as covering the branch.
    for m in muts:
        for _find, repl in m.get("edits", []):
            for why in home_escapes(repl):
                drift.append(f"mutation {m.get('name', '?')!r}: {why}. Its REPLACEMENT "
                             f"text is scanned as well as its target, because the "
                             f"mutation is what puts the route there")
    if drift:
        return False, drift, ev
    targets = sorted(counts)
    with tempfile.TemporaryDirectory() as td:
        d = pathlib.Path(td)
        shutil.copytree(root / "scripts", d / "scripts")
        # The redirected home the suites will resolve `Path.home()` to — see `child_env`.
        # Inside the TemporaryDirectory, so it is removed with everything else.
        (d / CHILD_HOME).mkdir()
        report = []
        # THE CONTROL, FIRST. Every 'caught' below claims the suite went red BECAUSE of
        # the mutation; that claim is empty unless the suite is green without it.
        for name in targets:
            rc, out = run_suite(d, name)
            ev["files"][name] = {"rc": rc, "tail": (out.split("\n")[-1] if out else ""),
                                 "blocks": None}
            if rc != 0:
                report.append(f"CANNOT RUN — control run of {name} exited {rc} BEFORE any "
                              f"mutation was applied. Every verdict below would be an "
                              f"artefact. Treat this as NOT CHECKED.\n    {out[-400:]}")
        if report:
            return False, report, ev
        ok, m_report, m_muts, m_survivors = run_mutations(d, muts, set(targets))
        ev["mutations"], ev["survivors"] = m_muts, m_survivors
        # THE CONTROL AGAIN, AFTER. A prologue proves the tree was good when we STARTED.
        # If it goes bad at mutation 17 — disk, OOM, a peer process — every later suite
        # exits 1, `run_mutations` only distinguishes rc==2, and an environmental red is
        # recorded as `caught` indistinguishably from a real one. Re-running on the
        # restored copy is what turns the control from a prologue into an invariant.
        for name in targets:
            rc, out = run_suite(d, name)
            if rc != 0:
                ok = False
                m_report.append(
                    f"CANNOT RUN — {name} is no longer green AFTER the sequence (exit "
                    f"{rc}), so the tree changed underneath it. Any 'caught' above may be "
                    f"an artefact of that, not of its mutation. Treat this run as NOT "
                    f"CHECKED.\n    {out[-400:]}")
        return ok, m_report, ev


def run_mutations(d: pathlib.Path, muts: list[dict],
                  known: set[str]) -> tuple[bool, list[str], list[dict], list[str]]:
    """Apply each mutation to a file in `d`, run its suite, require red via the named case.

    `d` holds runnable scripts — assembled from a plan, or copied from the delivered
    tree. This function does not care which, and that indifference is the point: the
    guarantee is about the mutation discipline, not where the code came from.

    NOTHING in the body changed when it was extracted (backlog #70, Task 1). Every
    guard below was bought with a review round, so a diff that alters behaviour is a
    defect in the refactor, not an improvement. Proof is a measurement, not a reading:
    43 mutations / 0 survivors before and after.
    """
    ok, report, ev_muts, ev_survivors = True, [], [], []
    for mut in muts:
        name, fname = mut.get("name", "?"), mut.get("file", "")
        if fname not in known:
            ok = False
            report.append(f"mutation {name!r} targets unknown file {fname!r}")
            continue
        src = (d / fname).read_text()
        for find, repl in mut.get("edits", []):
            # `replace(find, repl, 1)` takes the FIRST occurrence. If the anchor
            # matches more than once, the mutation may land on a test oracle
            # while the production line it names is untouched — and the named
            # case still goes red, so it reports `caught`. Measured round 5;
            # round 4's M1 filed the same hazard when a duplicated function
            # made it concrete. Deleting that duplicate removed the instance,
            # not the class.
            if src.count(find) > 1:
                ok = False
                report.append(
                    f"mutation {name!r}: anchor matches {src.count(find)} times "
                    f"in {fname} — only the FIRST is replaced, so a 'caught' "
                    f"verdict would not be about the line you named. Tighten it")
                src = None
                break
            if find not in src:
                ok = False
                report.append(f"mutation {name!r}: anchor NOT FOUND — it was not applied, "
                              f"so its 'caught' verdict would be meaningless")
                src = None
                break
            src = src.replace(find, repl, 1)
        if src is None:
            continue
        orig = (d / fname).read_text()
        (d / fname).write_text(src)
        rc, out = run_suite(d, fname)
        (d / fname).write_text(orig)
        # `  [FAIL] {name}: got {got!r} want {want!r}` — split on the LAST ": got ",
        # not the first ":". A case name may contain a colon ("collect: a missing
        # git is a could-not-tell"), and splitting on the first one truncated it to
        # "collect", so no `expect` naming the full case could ever match.
        # `l.strip()[7:]` assumes the line STARTS with "[FAIL] ". A line that
        # merely contains the marker (a log prefix, an ANSI escape) was sliced
        # blind and silently produced a wrong case name. Measured round 5.
        fails = [l.strip()[7:].rsplit(": got ", 1)[0].strip()
                 for l in out.split("\n") if l.strip().startswith("[FAIL] ")]
        # rc 2 is `run_suite`'s CANNOT RUN — a timeout. Reading it as red records
        # two minutes of NOT CHECKED as proof that a guard works, and prints
        # `caught <name>` into the evidence block. The comment on `run_suite`
        # said rc 2 must not be readable as either verdict and its very next
        # caller read it as one. Measured round 5, M2.
        if rc == 2:
            ok = False
            ev_muts.append({"name": name, "caught": False, "fails": fails})
            ev_survivors.append(name)
            report.append(
                f"mutation {name!r}: the suite did NOT COMPLETE ({out.strip()[:120]}). "
                f"That is a cannot-run, not a catch — treat this mutation as NOT CHECKED")
            continue
        caught = rc == 1
        # Each `expect` entry must name exactly ONE red case. As a bare substring
        # it could be satisfied by a DIFFERENT case than the mutation is about —
        # measured round 5 (M1): `expect: "does NOT count"` matches 7 case names
        # in this plan alone, and a fixture certified an untouched guard as caught
        # because a sibling case went red. The plan's rule is "red via the case it
        # NAMES"; the tool enforced "red via any case containing this substring".
        #
        # A mutation may legitimately break several behaviours, so `expect` accepts
        # a LIST — every entry must resolve to exactly one red case. That is more
        # honest than naming one of five arbitrarily and calling it the guard.
        #
        # ⚠ EXACT case names, not substrings (round 6). The round-5 rule was
        # CARDINALITY-ONLY: it required exactly one MATCH, never that the match
        # was the right case. Measured — an `expect` naming a completely
        # unrelated case, or a mere fragment of a name, still certified the
        # mutation. The plan's rule is "red via the case it NAMES"; only
        # equality says that.
        want = mut.get("expect")
        if isinstance(want, list) and not want:
            # An empty list read as "no expectation" — a declared-but-empty set
            # is a mistake, and silently honouring it disables the check.
            ok = False
            report.append(f"mutation {name!r}: `expect` is an EMPTY list. Name the "
                          f"case(s) that must go red, or omit `expect` entirely")
            continue
        wants = [want] if isinstance(want, str) else list(want or [])
        # ONE branch for both failure shapes. Zero matches means the mutation was
        # caught by something else; two or more means the expect cannot say which
        # case is the guard. Reporting them separately left the zero-match message
        # unreachable the moment the set form landed — dead code that two cases
        # were still asserting.
        unnamed = [(w, [f for f in fails if w == f]) for w in wants]
        unnamed = [(w, m) for w, m in unnamed if len(m) != 1]
        ev_muts.append({"name": name, "caught": caught, "fails": fails})
        if not caught:
            ok = False
            ev_survivors.append(name)
            report.append(f"mutation SURVIVED — {name}: the suite stayed green, so no case "
                          f"can fail for what it names")
        elif unnamed:
            ok = False
            for w, m in unnamed:
                report.append(
                    f"mutation {name!r}: `expect` {w!r} matched {len(m)} red case(s) "
                    f"{m or '— it was caught by something else: ' + str(fails)}. An "
                    f"expect must name EXACTLY ONE, or it cannot show which case is "
                    f"the guard")
    return ok, report, ev_muts, ev_survivors



def check(plan: pathlib.Path, compare: pathlib.Path | None = None) -> tuple[bool, list[str], dict]:
    md = plan.read_text(encoding="utf-8")
    files, muts, problems, tally = extract(md)
    report, ev = list(problems), {"files": {}, "mutations": [], "survivors": [],
                                  "tally": tally, "compared": None}
    if not files:
        report.append("no `<!-- file: … -->` tagged Python blocks found — nothing to assemble")
        return False, report, ev

    with tempfile.TemporaryDirectory() as td:
        d = pathlib.Path(td)
        # Same redirected home the mutation path gets, and it must EXIST here too. Codex
        # raised this against the first draft: `child_env` applies to every spawn, so
        # without this line a plan suite that writes to `Path.home()` used to pass under
        # the developer's real home and would now die on FileNotFoundError. That is a
        # behaviour change to the older mode, not the "costs zero fidelity" this claimed.
        (d / CHILD_HOME).mkdir()
        for name, blocks in files.items():
            (d / name).parent.mkdir(parents=True, exist_ok=True)
            (d / name).write_text("\n\n".join(blocks) + "\n", encoding="utf-8")
        ok = not problems
        if compare is not None:
            cmp_problems, ev["compared"] = compare_delivered(d, files, compare)
            if cmp_problems:
                ok = False
                report.extend(cmp_problems)
        for name in files:
            rc, out = run_suite(d, name)
            # EVERY result line, not just the last. A file with two suites (a pure
            # one and a cannot-run one) prints two summaries, and reporting only the
            # tail silently drops one of them from the evidence.
            results = [l.strip() for l in out.split("\n") if RESULT.search(l)]
            tail = " · ".join(results) or (out.split("\n")[-1] if out else "(no output)")
            ev["files"][name] = {"rc": rc, "tail": tail, "blocks": len(files[name])}
            if rc != 0:
                ok = False
                report.append(f"{name}: --self-test exited {rc}\n    {out[-600:]}")
            elif "passed" not in out:
                ok = False
                report.append(f"{name}: --self-test exited 0 but printed no result — "
                              f"a script with no entrypoint exits 0 silently. Got: {tail!r}")

        m_ok, m_report, m_muts, m_survivors = run_mutations(d, muts, set(files))
        if not m_ok:
            ok = False
        report.extend(m_report)
        ev["mutations"].extend(m_muts)
        ev["survivors"].extend(m_survivors)
    return ok, report, ev


def evidence(ev: dict) -> str:
    out = ["```", "GENERATED by scripts/check-plan-code.py — do not edit by hand.", ""]
    tl = ev.get("tally", {})
    if tl:
        out.append(f"  python fences: {tl['python_fences']} "
                   f"({tl['tagged']} assembled, {tl['illustrative']} illustrative)")
        # What was EXCLUDED, and why. An exclusion nobody can see is the hiding vector.
        for why in tl.get("illustrative_reasons", []):
            out.append(f"    not assembled: {why}")
        out.append("")
    for name, f in sorted(ev["files"].items()):
        out.append(f"  {name:28} {f['blocks']:>2} blocks assembled -> {f['tail']}")
    caught = sum(1 for m in ev["mutations"] if m["caught"])
    out.append("")
    # The subject is stated in the evidence itself, so a reader cannot mistake a
    # green over the plan's copy for a green over the delivered scripts (round 4 H1).
    cmp = ev.get("compared")
    if cmp is None:
        out.append("  subject: the PLAN'S COPY of the code. --compare was not given, so")
        out.append("           nothing here was measured against the files in scripts/.")
    else:
        out.append("  subject: the plan's blocks, DIFFED against the delivered files:")
        for name, verdict in sorted(cmp.items()):
            out.append(f"    {verdict:10} {name}")
    out.append("")
    out.append(f"  mutations declared and run: {len(ev['mutations'])}, caught {caught}")
    for m in ev["mutations"]:
        out.append(f"    {'caught  ' if m['caught'] else 'SURVIVED'} {m['name']}")
    out.append("```")
    return "\n".join(out)


EV_MARK = "GENERATED by scripts/check-plan-code.py — do not edit by hand."


def pasted_evidence(md: str) -> str | None:
    """The evidence block currently pasted into the plan, or None if there is none."""
    if md.count(EV_MARK) > 1:
        # A plan with a fresh block followed by a stale one passed, because only
        # the first was ever compared. Measured round 5. Ambiguity here is a
        # failure, not a choice of which to believe.
        return "AMBIGUOUS"
    i = md.find(EV_MARK)
    if i < 0:
        return None
    start = md.rfind("```", 0, i)
    end = md.find("\n```", i)
    if start < 0 or end < 0:
        return None
    return md[start:end + 4]


def verify_evidence(plan: pathlib.Path, ev: dict) -> list[str]:
    """FAIL if the pasted block is not what this run just produced.

    Round 4's Blocking: the block was generated at v4 and never again, so by v5 it
    reported 25 mutations against 26 and 77 tests against 79 — WRONG, inside the one
    mechanism built to stop the plan being wrong about its own verification. Being
    generated bought provenance, not freshness. A derived artifact that is not
    re-derived on every change is a cached claim, and a cached claim with a
    `GENERATED` header is read with MORE trust than typed prose, not less.
    """
    pasted = pasted_evidence(plan.read_text(encoding="utf-8"))
    if pasted == "AMBIGUOUS":
        return ["--verify-evidence: the plan contains MORE THAN ONE generated "
                "evidence block. Only one can be the current one, and checking the "
                "first would leave the others free to go stale. Treat as NOT CHECKED."]
    if pasted is None:
        return ["--verify-evidence: no generated evidence block found in the plan "
                "(looked for the GENERATED header). Treat this as NOT CHECKED."]
    fresh = evidence(ev)
    if pasted.strip() == fresh.strip():
        return []
    diff = list(difflib.unified_diff(pasted.strip().split("\n"), fresh.split("\n"),
                                     fromfile="pasted in the plan",
                                     tofile="generated by this run", lineterm=""))
    mode = ("--compare " + str(ev["compared"] and "<dir>" or "")).strip() if ev.get(
        "compared") is not None else "(no --compare)"
    return [f"--verify-evidence: the pasted evidence block is STALE. It describes a "
            f"different run than the one that just happened, which was {mode}. "
            f"⚠ The block is INVOCATION-SPECIFIC: a compared run and a bare run "
            f"produce different blocks, so regenerate with the SAME flags the "
            f"gate uses.\n    " + "\n    ".join(diff[:40])]


def count_drift(doc: str | None, actual: int) -> str | None:
    """None if the docstring's declared case count matches `actual`, else why not.

    A module-level function so the suite can cover it. As an inline block at the end
    of `_self_test` it was unreachable from any case, and deleting it outright left
    the suite green — measured round 5.
    """
    m = re.search(r"--self-test\s+#\s*(\d+) cases", doc or "")
    if not m:
        return "CANNOT RUN — the docstring no longer declares a case count."
    if int(m.group(1)) != actual:
        return f"[DRIFT] the docstring declares {m.group(1)} cases; the suite ran {actual}"
    return None


def _drift_rc(doc: str | None, ok: int, fail: int) -> int:
    """The suite's exit code, drift included. Prints the drift line if there is one.

    A helper because the DECISION was the untested part. Round 5 extracted
    `count_drift` so the suite could reach it — and three cases do — but the call
    that makes it load-bearing was still inline, so deleting it left 92/92 green.
    Extracting the function bought coverage of the function; the wiring inherited
    the same blind spot. Round 6, M5.
    """
    drift = count_drift(doc, ok + fail)
    if drift:
        print(f"  {drift}")
        return 1
    return 1 if fail else 0


def _self_test() -> int:
    ok = fail = 0

    def case(name, got, want):
        nonlocal ok, fail
        if got == want:
            ok += 1
        else:
            fail += 1
            print(f"  [FAIL] {name}: got {got!r} want {want!r}")

    # The fixture emits a real [FAIL] line, so the `expect` path is genuinely
    # exercised rather than passing because the list is empty.
    GOOD = ('<!-- file: m.py -->\n```python\ndef f():\n    return 1\n\n\n'
            'def _self_test():\n'
            '    bad = f() != 1\n'
            '    if bad:\n'
            '        print("  [FAIL] f returns one: got %r" % f())\n'
            '    print("%d/1 passed" % (0 if bad else 1))\n'
            '    return 1 if bad else 0\n\n\n'
            'import sys\nif __name__ == "__main__":\n    sys.exit(_self_test())\n```\n')
    # ⚠ The anchor is `def f():\\n    return 1`, not the bare `return 1`. The bare
    # form matches TWICE in GOOD (the production line and `return 1 if bad else 0`),
    # and an ambiguous anchor is now refused — correctly: `replace(…, 1)` takes the
    # first, which need not be the line the mutation names. This fixture carried
    # that ambiguity from the day it was written, and the new check found it.
    MUTS = ('<!-- mutations -->\n```json\n'
            '[{"name": "f returns 2", "file": "m.py",'
            ' "edits": [["def f():\\n    return 1", "def f():\\n    return 2"]],'
            ' "expect": "f returns one"}]\n```\n')

    files, muts, probs, tally = extract(GOOD + MUTS)
    case("one file extracted", list(files), ["m.py"])
    case("one mutation extracted", len(muts), 1)
    case("no problems on a well-formed plan", probs, [])
    case("the tally counts one tagged python fence", (tally["python_fences"], tally["tagged"]), (1, 1))
    _f, _m, p2, t2 = extract('```python\nx = 1\n```\n')
    case("an UNTAGGED python block is a problem", len(p2), 1)
    _f, _m, p3, t3 = extract('<!-- illustrative: a fragment, shown for context -->\n'
                             '```python\nx = 1\n```\n')
    case("an explicitly ILLUSTRATIVE block with a reason is not", p3, [])
    case("...and is counted as such", t3["illustrative"], 1)
    case("...and its reason is recorded for the evidence block",
         t3["illustrative_reasons"], ["a fragment, shown for context"])
    # A bare tag excuses a block from every check here with no account of why.
    _f, _m, p3b, _t = extract('<!-- illustrative -->\n```python\nx = 1\n```\n')
    # TWO problems, and that is right: the tag is rejected, and the block it was
    # meant to excuse is then simply untagged. Fail closed in both directions.
    case("a BARE illustrative tag (no reason) is a problem", len(p3b), 2)
    case("...and it says a REASON is required", any("REASON" in p for p in p3b), True)
    case("...and the block it failed to excuse is reported as UNTAGGED",
         any("UNTAGGED" in p for p in p3b), True)

    _, _, p, _t = extract('<!-- file: a.py -->\n<!-- file: b.py -->\n```python\nx = 1\n```\n')
    case("a tag followed by another tag is a problem", len(p), 1)
    _, _, p, _t = extract("<!-- file: a.py -->\nno block follows\n")
    case("a tag with no block is a problem", len(p), 1)
    _, _, p, _t = extract('<!-- file: a.py -->\n```bash\necho hi\n```\n')
    case("a non-python block under a file tag is a problem", len(p), 1)
    _, _, p, _t = extract('<!-- mutations -->\n```json\nnot json\n```\n')
    case("an unparseable mutations block is a problem", len(p), 1)

    with tempfile.TemporaryDirectory() as td:
        pl = pathlib.Path(td) / "p.md"
        pl.write_text(GOOD + MUTS)
        good_ok, rep, ev = check(pl)
        case("a well-formed plan passes", good_ok, True)
        case("its mutation is recorded as caught", ev["mutations"][0]["caught"], True)

        # A script with no entrypoint exits 0 and prints nothing — r3's Blocking.
        pl.write_text('<!-- file: m.py -->\n```python\ndef f():\n    return 1\n```\n')
        silent_ok, rep, _ = check(pl)
        case("a file with no entrypoint FAILS rather than passing silently", silent_ok, False)
        case("...and says why", any("no entrypoint" in r for r in rep), True)

        # A mutation whose anchor is absent was never applied.
        pl.write_text(GOOD + '<!-- mutations -->\n```json\n'
                      '[{"name": "ghost", "file": "m.py", "edits": [["nope", "x"]]}]\n```\n')
        ghost_ok, rep, _ = check(pl)
        case("a mutation whose anchor is missing FAILS", ghost_ok, False)

        # A case name containing a colon must still be matchable by `expect`.
        COLON = GOOD.replace("f returns one", "f: returns one")
        pl.write_text(COLON + '<!-- mutations -->\n```json\n'
                      '[{"name": "colon", "file": "m.py",'
                      ' "edits": [["def f():\\n    return 1", "def f():\\n    return 2"]],'
                      ' "expect": "f: returns one"}]\n```\n')
        colon_ok, rep, _ = check(pl)
        case("an `expect` matches a case name containing a COLON", colon_ok, True)

        # A mutation that goes red via a DIFFERENT case than the one named is
        # not evidence for the case it claims — r3's day-anchor shape.
        pl.write_text(GOOD + '<!-- mutations -->\n```json\n'
                      '[{"name": "wrong case", "file": "m.py",'
                      ' "edits": [["def f():\\n    return 1", "def f():\\n    return 2"]],'
                      ' "expect": "some other case"}]\n```\n')
        wrong_ok, rep, _ = check(pl)
        case("a mutation caught by the WRONG case fails", wrong_ok, False)
        case("...and says it was caught by something else",
             any("caught by something else" in r for r in rep), True)

        # A surviving mutation must fail the check.
